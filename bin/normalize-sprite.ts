// Dev-only, one-time tool. Run via:
//   tsx bin/normalize-sprite.ts <path.json|path.ts> [exportName] [varName]
//
// Reads a panel-absolute "x:y" -> hex coordinate map (a custom_scenes/*.json
// file, or a named export from a .ts module) and prints a ready-to-paste
// TS module with the map rebased to its own bounding box (minX = minY = 0).
//
// The output is meant to be committed by hand into src/scenes/<name>/sprite.ts,
// not regenerated at build or render time — the coordinates are the art.

import { readFileSync } from "fs";
import { resolve } from "path";
import { measure, normalizeSprite } from "../src/scenes/sprite-utils";

async function main() {
  const [inputPath, exportName, varNameArg] = process.argv.slice(2);

  if (!inputPath) {
    console.error(
      "Usage: tsx bin/normalize-sprite.ts <path.json|path.ts> [exportName] [varName]",
    );
    process.exit(1);
  }

  let coords: { [key: string]: string };

  if (inputPath.endsWith(".json")) {
    coords = JSON.parse(readFileSync(inputPath, "utf-8"));
  } else {
    const mod = await import(resolve(inputPath));
    const key = exportName ?? Object.keys(mod)[0];
    coords = mod[key];
    if (!coords) {
      console.error(`Export "${key}" not found in ${inputPath}`);
      process.exit(1);
    }
  }

  const before = measure(coords);
  const sprite = normalizeSprite(coords);

  const varName =
    varNameArg ??
    `${inputPath
      .split("/")
      .pop()!
      .replace(/\.(json|ts)$/, "")}Sprite`;

  console.error(
    `// source extent: x${before.minX}-${before.maxX}, y${before.minY}-${before.maxY} ` +
      `(${before.width}x${before.height}), ${Object.keys(coords).length} keys`,
  );

  const pixelLines = Object.entries(sprite.pixels)
    .map(([k, v]) => `  "${k}": "${v}",`)
    .join("\n");

  console.log(
    `// GENERATED by bin/normalize-sprite.ts from ${inputPath}, then hand-tuned.\n` +
      `import { Sprite } from "../sprite";\n\n` +
      `export const ${varName}: Sprite = {\n` +
      `  width: ${sprite.width},\n` +
      `  height: ${sprite.height},\n` +
      `  pixels: {\n${pixelLines}\n  },\n` +
      `};\n`,
  );
}

main();
